    def generate_plan(self, task: str, context: Dict[str, Any]) -> ExecutionPlan:
        steps = []
        task_lower = task.lower()

        # Check for explicit file mentions (e.g. "create src/calculator.py" or "hello.py")
        file_match = re.search(r'([\w\-./\\]+\.(py|tsx|ts|jsx|js|go|json|md|html|css))', task)

        target_file = file_match.group(1).replace("\\", "/") if file_match else None

        if target_file:
            # 1. Create directory if needed
            if "/" in target_file:
                dir_path = target_file.rsplit("/", 1)[0]
                steps.append(
                    PlanStep(
                        title=f"Create directory: {dir_path}",
                        description=f"Ensure parent directory structure exists for {target_file}",
                        operation=OperationType.CREATE_DIR,
                        path=dir_path,
                        risk_level=RiskLevel.LOW,
                        requires_approval=False,
                    )
                )

            # 2. Create target file
            content = self._generate_code_snippet(target_file, task)
            steps.append(
                PlanStep(
                    title=f"Create file: {target_file}",
                    description=f"Write implementation for task: {task}",
                    operation=OperationType.CREATE_FILE,
                    path=target_file,
                    content=content,
                    risk_level=RiskLevel.LOW,
                    requires_approval=True,
                )
            )

            # 3. Add verification command if python or ts
            if target_file.endswith(".py"):
                steps.append(
                    PlanStep(
                        title=f"Verify execution of {target_file}",
                        description=f"Execute {target_file} via python to verify functionality",
                        operation=OperationType.RUN_COMMAND,
                        command=f"python {target_file}",
                        risk_level=RiskLevel.MEDIUM,
                        requires_approval=True,
                    )
                )

        elif "test" in task_lower:
            steps.append(
                PlanStep(
                    title="Run test suite",
                    description="Execute automated tests to detect regressions or verify functionality",
                    operation=OperationType.RUN_COMMAND,
                    command="python -m pytest tests" if "FastAPI" in context.get("tech_stack", []) else "npm test",
                    risk_level=RiskLevel.LOW,
                    requires_approval=True,
                )
            )

        else:
            # Default structured scaffolding task
            default_path = "kodra_task.py"
            content = self._generate_code_snippet(default_path, task)
            steps.append(
                PlanStep(
                    title=f"Generate task implementation: {default_path}",
                    description=f"Construct module addressing request: {task}",
                    operation=OperationType.CREATE_FILE,
                    path=default_path,
                    content=content,
                    risk_level=RiskLevel.LOW,
                    requires_approval=True,
                )
            )
            steps.append(
                PlanStep(
                    title="Validate task implementation",
                    description=f"Run python {default_path} to verify script runs cleanly",
                    operation=OperationType.RUN_COMMAND,
                    command=f"python {default_path}",
                    risk_level=RiskLevel.MEDIUM,
                    requires_approval=True,
                )
            )

        return ExecutionPlan(
            task=task,
            summary=f"Execution plan to fulfill request: '{task}' with {len(steps)} planned operations.",
            steps=steps,
            status=PlanStatus.DRAFT,
            metadata={"provider": "mock", "context_keys": list(context.keys())},
        )

    def analyze_failure(
        self,
        task: str,
        step: PlanStep,
        error_output: str,
        context: Dict[str, Any],
    ) -> ExecutionPlan:
        err_line = error_output.strip().splitlines()[-1] if error_output.strip() else "Unknown execution error"
        repair_step = PlanStep(
            title=f"Fix failure in: {step.title}",
            description=f"Apply correction addressing error: {err_line}",
            operation=step.operation,
            path=step.path,
            content=step.content,
            command=step.command,
            risk_level=RiskLevel.MEDIUM,
            requires_approval=True,
        )
        return ExecutionPlan(
            task=f"Repair failure for task: {task}",
            summary=f"Diagnostic repair plan resolving: {err_line}",
            steps=[repair_step],
            status=PlanStatus.DRAFT,
            metadata={"is_repair": True, "error": err_line},
        )

    def chat(self, message: str, context: Dict[str, Any]) -> str:
        current_file = context.get("currentFile")
        tech_stack = ", ".join(context.get("tech_stack", [])) or "Full-Stack"
        if current_file:
            return (
                f"I've inspected {current_file} in your {tech_stack} project. "
                f"I am ready to formulate an execution plan to: '{message}'. "
                "Submit a task plan whenever you're ready to proceed."
            )
        return (
            f"Kodra AI ({tech_stack}) is active. "
            f"You asked: '{message}'. Describe what you'd like built, modified, or tested, "
            "and I will generate an actionable execution plan for your approval."
        )
